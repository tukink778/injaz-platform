-- الهجرات m0002/m0003 تضيف أعمدة الطالب وجداول ربط البريد (انظر app/migrations).

CREATE TABLE IF NOT EXISTS departments(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL, name_ar TEXT NOT NULL, name_en TEXT NOT NULL DEFAULT '',
  active BIGINT NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS users(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT UNIQUE NOT NULL, full_name TEXT NOT NULL, email TEXT NOT NULL DEFAULT '',
  pw_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN('admin','manager','organizer','viewer')),
  dept_id BIGINT REFERENCES departments(id), active BIGINT NOT NULL DEFAULT 1,
  must_change_pw BIGINT NOT NULL DEFAULT 1, totp_secret TEXT, failed BIGINT NOT NULL DEFAULT 0,
  locked_until BIGINT NOT NULL DEFAULT 0, session_ver BIGINT NOT NULL DEFAULT 1,
  created_at BIGINT NOT NULL, last_login BIGINT);
CREATE TABLE IF NOT EXISTS templates(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, config TEXT NOT NULL, builtin BIGINT NOT NULL DEFAULT 0,
  active BIGINT NOT NULL DEFAULT 1, created_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS events(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dept_id BIGINT NOT NULL REFERENCES departments(id),
  title_ar TEXT NOT NULL, title_en TEXT NOT NULL DEFAULT '', category TEXT NOT NULL DEFAULT 'training',
  template_id BIGINT NOT NULL REFERENCES templates(id),
  event_date TEXT NOT NULL, end_date TEXT, hours DOUBLE PRECISION NOT NULL DEFAULT 0, location TEXT NOT NULL DEFAULT '',
  signatory_name TEXT NOT NULL DEFAULT '', signatory_title_ar TEXT NOT NULL DEFAULT '', signatory_title_en TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'draft', reg_token TEXT UNIQUE NOT NULL, reg_open BIGINT NOT NULL DEFAULT 0,
  reg_opens_at TEXT, reg_closes_at TEXT, reg_pin TEXT NOT NULL DEFAULT '', max_participants BIGINT NOT NULL DEFAULT 0,
  auto_approve BIGINT NOT NULL DEFAULT 0, require_uid BIGINT NOT NULL DEFAULT 1, require_spec BIGINT NOT NULL DEFAULT 0,
  rows_total BIGINT NOT NULL DEFAULT 0, rows_invalid BIGINT NOT NULL DEFAULT 0,
  created_by BIGINT REFERENCES users(id), created_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS participants(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  name_enc TEXT NOT NULL, name_en_enc TEXT NOT NULL DEFAULT '', uid_enc TEXT NOT NULL DEFAULT '', uid_idx TEXT NOT NULL DEFAULT '',
  email_enc TEXT NOT NULL DEFAULT '', email_idx TEXT NOT NULL DEFAULT '', specialization TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL DEFAULT 'manual', status TEXT NOT NULL DEFAULT 'pending',
  checked_in_at BIGINT, created_at BIGINT NOT NULL, dedupe TEXT NOT NULL,
  UNIQUE(event_id, dedupe));
CREATE INDEX IF NOT EXISTS ix_part_uid ON participants(uid_idx);
CREATE INDEX IF NOT EXISTS ix_part_email ON participants(email_idx);
CREATE TABLE IF NOT EXISTS certificates(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, participant_id BIGINT NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  serial TEXT UNIQUE NOT NULL, verify_code TEXT UNIQUE NOT NULL, name_enc TEXT NOT NULL,
  issued_at BIGINT NOT NULL, issued_by BIGINT REFERENCES users(id), file TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'valid', revoked_at BIGINT, revoked_reason TEXT NOT NULL DEFAULT '',
  email_status TEXT NOT NULL DEFAULT 'none', email_sent_at BIGINT, email_error TEXT NOT NULL DEFAULT '',
  dl_hash TEXT NOT NULL DEFAULT '', dl_expires BIGINT NOT NULL DEFAULT 0, downloads BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS counters(name TEXT PRIMARY KEY, val BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS audit(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts BIGINT NOT NULL, user_id BIGINT, username TEXT, ip TEXT, action TEXT NOT NULL,
  target TEXT, detail TEXT, prev_hash TEXT NOT NULL, hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS rate(key TEXT NOT NULL, ts BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS ix_rate ON rate(key, ts);
CREATE TABLE IF NOT EXISTS portal_tokens(token_hash TEXT PRIMARY KEY, uid_idx TEXT NOT NULL DEFAULT '', email_idx TEXT NOT NULL DEFAULT '', expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS jobs(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL, event_id BIGINT, user_id BIGINT, status TEXT NOT NULL DEFAULT 'running',
  total BIGINT NOT NULL DEFAULT 0, done BIGINT NOT NULL DEFAULT 0, failed BIGINT NOT NULL DEFAULT 0,
  message TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL);
